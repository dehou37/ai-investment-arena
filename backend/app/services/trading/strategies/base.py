
from abc import ABC, abstractmethod
from typing import Any

from app.schemas.agent_decision import AgentDecision


class TradingStrategy(ABC):
    """
    Base interface for all autonomous trading strategies.

    Each strategy receives the same market context and returns
    a validated AgentDecision.

    Strategies must not:
    - Submit orders.
    - Modify portfolios.
    - Access the database directly.
    - Access market data outside the supplied context.
    """

    strategy_type: str

    @abstractmethod
    def generate_decision(
        self,
        context: dict[str, Any],
    ) -> AgentDecision:
        """
        Generate trading decisions using the supplied market context.

        Args:
            context: Market and portfolio context generated by
                     market_context_service.

        Returns:
            An AgentDecision containing the strategy's decisions.
        """
        raise NotImplementedError
